create or replace function name_tokens(p_full_name text)
returns text[]
language sql
immutable
as $$
  select coalesce(array_agg(tok order by ord), '{}')
  from (
    select replace(t, '"', '') as tok, ord
    from regexp_split_to_table(
           regexp_replace(translate(coalesce(p_full_name, ''), '״׳', '"'''),
                          '[][(){}.,;:!?/\\־–-]', ' ', 'g'),
           '\s+') with ordinality as x(t, ord)
    where t <> ''
      and t not in ('עו"ד', 'עוה"ד', 'ד"ר', 'דר''', 'פרופ''', 'פרופ', 'מר', 'גב''', 'גברת',
                    'הרב', 'הרבנית', 'משפחת', 'משפ''', 'חברת', 'חב''', 'בע"מ', 'עמותת',
                    'דייר', 'דיירים', 'הזוג')
  ) s
  where tok <> ''
$$;

comment on function name_tokens(text) is
  'The words of a resident''s name, titles and household words removed. See 038.';

create or replace function name_gender(p_full_name text)
returns text
language plpgsql
stable
as $$
declare
  tk text[] := name_tokens(p_full_name);
  n  int    := coalesce(array_length(tk, 1), 0);
  g  text;
begin
  if n = 0 then
    return null;
  end if;
  -- A surname opening with בן / בר / בת / אבו / אבן / בית, written first.
  if n >= 3 and tk[1] in ('בן', 'בר', 'בת', 'אבו', 'אבן', 'בית') then
    select f.gender into g from first_name_gender f where f.name = tk[3];
    if g in ('m', 'f') then
      return g;
    end if;
  end if;
  -- The first word decides when it can.
  g := null;
  select f.gender into g from first_name_gender f where f.name = tk[1];
  if g in ('m', 'f') then
    return g;
  end if;
  if g = 'u' then
    return null;            -- a name for both: undecided, never guessed
  end if;
  -- The first word is not a name we know: a surname written first.
  if n >= 2 then
    g := null;
    select f.gender into g from first_name_gender f where f.name = tk[2];
    if g in ('m', 'f') then
      return g;
    end if;
  end if;
  return null;
end
$$;

comment on function name_gender(text) is
  'm or f from a full name, NULL when the name does not decide. The rules are in '
  'the header of 038.';

-- One resident's gender as the call will use it: the value a person set, else the
-- name, else unknown. Takes the row, so PostgREST exposes it as a computed field:
-- the Debts page selects residents(…, call_gender) and shows it before the press.
create or replace function call_gender(r residents)
returns text
language sql
stable
as $$
  select coalesce(r.gender, name_gender(r.full_name), 'unknown')
$$;

comment on function call_gender(residents) is
  'How the debt call will address this resident: m, f or unknown. residents.gender '
  'wins, then name_gender(full_name). A PostgREST computed field. See 038.';

grant execute on function name_tokens(text)      to authenticated;
grant execute on function name_gender(text)      to authenticated;
grant execute on function call_gender(residents) to authenticated;

