-- 038 — the debt call addresses one person, in the gender their name gives
--
-- Owner, 30 Sep: "i dont want that because it means im multiple people it should
-- depend the gender based on the name for the debt collection", then "the way we
-- address the person is through the name we check if the name is female or male".
-- Until today the debt agent spoke to everyone in the plural (אתם, שלכם, תרצו),
-- because Hebrew has no neutral "you" and nothing knew anybody's gender:
-- residents.gender (004) is NULL on every real row and OXS sends none.
--
-- WHY IN THE DATABASE AND NOT IN THE PROMPT
-- The prompt tried deciding from the name itself on 9 Aug and dropped it on
-- 30 Aug: a model deciding per call slips (יוסי got תשלחי on 12 Aug). This makes
-- the decision once, in code, from a curated list, and hands the call a finished
-- instruction through the plumbing that already exists: v_debt_call_queue ->
-- v_debt_call_queue_person -> press_call / the Voice page -> dashboard/lib/call.ts
-- `gender` and `gender_forms` -> {{gender_forms}} in the prompt.
--
-- THE ORDER OF AUTHORITY
--   residents.gender set by a person ('m' / 'f' / 'unknown')  wins;
--   else the first name, through name_gender();
--   else 'unknown', which the call treats as masculine singular until the person
--   speaks of themselves in the feminine.
-- OXS re-imports never write residents.gender (oxs_api_import.py upserts without
-- it), so a value set by hand survives the twice-daily sync.
--
-- THE LIST
-- m / f only where Israelis give the name to one gender; u where it is really
-- used for both (עדי, טל, ליאור, שי, גל, אור, רוני, שחר, יובל…), and a u is never
-- guessed from. Written for this, measured against the live residents on 30 Sep
-- (names counted, never printed): 80% decided by the name, 16% a name used for
-- both, 4% no recognisable first name (a surname alone, a company, "משרד").
-- A name to add or correct goes in a NEW migration, `on conflict do update`;
-- this file is in the ledger once applied and is never edited.
--
-- THE MATCH (name_gender)
--   1. Tokens: ״ ׳ normalised, punctuation and hyphens split, titles and
--      household words dropped (עו"ד, ד"ר, מר, גב', הרב, משפחת, דייר…).
--   2. A surname that opens with בן / בר / בת / אבו / אבן / בית, written first
--      ("בן דוד שרה"): the third word, if it is a name.
--   3. The first word, if it is m or f. It wins even when the second word is a
--      name of the other gender: on 30 Sep the 408 such rows were nearly all a
--      first name followed by a surname that is also a name (אורלי ברק, עופר שני).
--   4. The first word is a known both-genders name: undecided.
--   5. The second word, if it is m or f (a surname written first: "כהן דנה").
--
-- No `begin`/`commit`: supabase_migrate.py runs each file in its own transaction.

create table if not exists first_name_gender (
  name   text primary key,
  gender text not null check (gender in ('m', 'f', 'u'))
);

comment on table first_name_gender is
  'Israeli first names and the gender they give: m, f, or u (used for both, never '
  'guessed from). Read by name_gender(). Curated by hand; add or correct a name in a '
  'new migration with on conflict do update. See 038.';

alter table first_name_gender enable row level security;
drop policy if exists staff_read on first_name_gender;
create policy staff_read on first_name_gender for select to authenticated using (true);
grant select on first_name_gender to authenticated;

